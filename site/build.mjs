#!/usr/bin/env node
// Bundles site/src/ into one self-contained site/index.html (the pattern of
// magic-c-builder and USM-web).
//
// Inputs: src/template.html ({{STYLES}}, {{CONSENT}}, {{SCRIPT}} markers),
// src/styles.css, src/consent.html with src/vendor/cookieconsent.{css,js},
// and src/<module>.js in MODULE_ORDER. Output: index.html (committed).
//
// The modules use ESM import/export so Node tests can load them directly;
// the build strips those keywords because the page runs them in a single
// module scope.

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');

// Each module may use names from the modules above it.
const MODULE_ORDER = [
  'sha256.js',
  'jackrom.js',
  'help-content.js',
  'builder.js',
  'how.js',
  'router.js',
  'app.js',
];

function stripEsm(source) {
  let out = source;
  out = out.replace(/^\s*import\s+[^;]*?from\s+['"][^'"]+['"]\s*;?\s*$/gm, '');
  out = out.replace(/^\s*import\s+['"][^'"]+['"]\s*;?\s*$/gm, '');
  out = out.replace(/^\s*export\s+(?=(function|const|let|var|class|async\s+function)\b)/gm, '');
  if (/^\s*export\s+(default\b|\{)/m.test(out)) {
    throw new Error('build: `export default` and `export { ... }` are not supported in src/ modules');
  }
  return out;
}

// SOFTWARE.md (the repository's list of programs, System 6.0.8 and what was
// tested) as HTML: headings, paragraphs, bullet lists and tables, with
// links, bold, italics and code; enough for that one file.
function inline(text) {
  return text
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/&lt;(https?:\/\/[^&]+)&gt;/g, '<a href="$1" target="_blank" rel="noopener">$1</a>')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>');
}

// A cell's colour, by column (Program, Model, System, Tested, Works, Notes):
// under Works yes green, no red, untested yellow; under Tested yes green and
// no (not tested yet) plain.
function cellClass(text, column) {
  const t = text.trim().toLowerCase();
  if (column === 3) return t === 'no' ? ' class="none"' : ' class="ok"';
  if (column !== 4) return '';
  if (t === 'yes') return ' class="ok"';
  if (t === 'no') return ' class="no"';
  if (t === '—') return ' class="try"';
  return '';
}

export function softwareHtml(markdown) {
  const out = [];
  const lines = markdown.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.startsWith('# ')) continue; // the page has its own title
    if (line.startsWith('## ')) { out.push(`<h3>${inline(line.slice(3))}</h3>`); continue; }
    if (line.startsWith('|')) {
      const rows = [];
      while (i < lines.length && lines[i].startsWith('|')) rows.push(lines[i++]);
      i--;
      const cells = (row) => row.split('|').slice(1, -1).map((c) => c.trim());
      const head = cells(rows[0]);
      const body = rows.slice(2).map(cells);
      out.push('<div class="table-wrap"><table class="software"><thead><tr>'
        + head.map((h) => `<th>${inline(h)}</th>`).join('') + '</tr></thead><tbody>'
        + body.map((r) => '<tr>' + r.map((c, k) => `<td${cellClass(c, k)}>${inline(c)}</td>`).join('') + '</tr>').join('')
        + '</tbody></table></div>');
      continue;
    }
    if (line.startsWith('- ')) {
      const items = [];
      while (i < lines.length && (lines[i].startsWith('- ') || lines[i].startsWith('  '))) {
        if (lines[i].startsWith('- ')) items.push(lines[i].slice(2)); else items[items.length - 1] += ' ' + lines[i].trim();
        i++;
      }
      i--;
      out.push('<ul>' + items.map((t) => `<li>${inline(t)}</li>`).join('') + '</ul>');
      continue;
    }
    if (line.trim() === '') continue;
    const para = [line];
    while (i + 1 < lines.length && lines[i + 1].trim() !== '' && !/^(#|\||- )/.test(lines[i + 1])) para.push(lines[++i]);
    out.push(`<p>${inline(para.join(' '))}</p>`);
  }
  return out.join('\n');
}

function main() {
  const parts = ['// AUTOGENERATED by build.mjs, do not hand-edit index.html.', ''];
  for (const name of MODULE_ORDER) {
    parts.push(`// ----- ${name} -----`);
    parts.push(stripEsm(readFileSync(join(SRC, name), 'utf8')).trimEnd());
    parts.push('');
  }
  // All modules share one scope in the page: fail here on a duplicate
  // top-level name or a syntax error instead of shipping a dead page.
  try {
    new Function(parts.join('\n'));
  } catch (err) {
    throw new Error(`build: the bundled script does not compile: ${err.message}`);
  }
  // Cookie banner and analytics, shared with sidecartridge.com.
  const consent = readFileSync(join(SRC, 'consent.html'), 'utf8')
    .replace('{{COOKIE_CSS}}', () => readFileSync(join(SRC, 'vendor', 'cookieconsent.css'), 'utf8').trim())
    .replace('{{COOKIE_JS}}', () => readFileSync(join(SRC, 'vendor', 'cookieconsent.js'), 'utf8').trim());
  let out = readFileSync(join(SRC, 'template.html'), 'utf8');
  out = out.replace('{{CONSENT}}', () => consent.trimEnd());
  out = out.replace('{{STYLES}}', () => readFileSync(join(SRC, 'styles.css'), 'utf8').trimEnd());
  out = out.replace('{{SCRIPT}}', () => parts.join('\n').trimEnd());
  out = out.replace('{{SOFTWARE}}', () => softwareHtml(readFileSync(join(ROOT, '..', 'SOFTWARE.md'), 'utf8')));
  // Each assets/ file referenced gets its content's fingerprint (?v=), so a
  // changed image is not served from a browser's or the CDN's cache.
  out = out.replace(/(['"(])assets\/([\w.-]+\.(?:jpg|png|svg|webp|gif))/g, (match, quote, name) => {
    const digest = createHash('sha256').update(readFileSync(join(ROOT, 'assets', name))).digest('hex');
    return `${match}?v=${digest.slice(0, 8)}`;
  });
  out = out.replace(/\r\n/g, '\n');
  if (!out.endsWith('\n')) out += '\n';
  writeFileSync(join(ROOT, 'index.html'), out);
  console.log(`build: index.html written (${out.length} bytes)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
